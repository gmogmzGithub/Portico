#!/usr/bin/env python3
"""Classify Snowflake setup progress without returning configuration values."""

from __future__ import annotations

import argparse
import json
from pathlib import Path
import re
import stat
import tomllib

try:
    import yaml
except ModuleNotFoundError:  # Production Agent VM images include PyYAML.
    yaml = None


MAX_CONFIG_BYTES = 1024 * 1024
SECURE_STUB_MARKER = (
    "# Portico imported this sensitive runtime file into secure storage."
)
REQUIRED_CONNECTION_FIELDS = (
    "account",
    "user",
    "role",
    "warehouse",
    "database",
    "schema",
)
# The credential lives in `token` (current generated shape, read by the
# connector's PAT authenticator) or `password` (hand-written PAT-as-password
# files and legacy generated files).
CREDENTIAL_CONNECTION_FIELDS = ("token", "password")


class SafeArgumentParser(argparse.ArgumentParser):
    def error(self, _message: str) -> None:
        raise ValueError("invalid_arguments")


def parse_args() -> argparse.Namespace:
    parser = SafeArgumentParser(add_help=False)
    parser.add_argument("--output-dir", default="/work")
    return parser.parse_args()


GENERATED_CONNECTIONS_MARKER = "# Generated by Portico Snowflake Setup."


def base_result(
    state: str, *, issue_code: str | None = None, generated: bool = False
) -> dict[str, object]:
    return {
        "state": state,
        "issue_code": issue_code,
        "missing_fields": [],
        "generated": generated,
    }


def read_fixed_file(path: Path) -> tuple[bytes | None, str | None]:
    try:
        metadata = path.lstat()
    except FileNotFoundError:
        return None, "absent"
    except OSError:
        return None, "stat_failed"
    if not stat.S_ISREG(metadata.st_mode):
        return None, "non_regular_file"
    if metadata.st_size > MAX_CONFIG_BYTES:
        return None, "file_too_large"
    try:
        return path.read_bytes(), None
    except OSError:
        return None, "read_failed"


def classify_connections(path: Path) -> dict[str, object]:
    raw, issue = read_fixed_file(path)
    if issue == "absent":
        return base_result("absent")
    if issue:
        return base_result("invalid", issue_code=issue)
    try:
        text = (raw or b"").decode("utf-8")
    except UnicodeDecodeError:
        return base_result("invalid", issue_code="invalid_utf8")

    if text.splitlines()[:1] == [SECURE_STUB_MARKER]:
        return base_result("secure_stub")

    generated = text.startswith(GENERATED_CONNECTIONS_MARKER)

    try:
        parsed = tomllib.loads(text)
    except (tomllib.TOMLDecodeError, ValueError):
        return base_result("invalid", issue_code="parse_error", generated=generated)

    connection = parsed.get("default")
    if not isinstance(connection, dict):
        result = base_result(
            "incomplete",
            issue_code="missing_default_connection",
            generated=generated,
        )
        result["missing_fields"] = list(REQUIRED_CONNECTION_FIELDS)
        return result

    missing = [
        field
        for field in REQUIRED_CONNECTION_FIELDS
        if not isinstance(connection.get(field), str) or not connection.get(field, "").strip()
    ]
    credentials = [
        field
        for field in CREDENTIAL_CONNECTION_FIELDS
        if isinstance(connection.get(field), str) and connection.get(field, "").strip()
    ]
    if not credentials:
        missing.append("token")
    if missing:
        result = base_result(
            "incomplete", issue_code="missing_required_fields", generated=generated
        )
        result["missing_fields"] = missing
        return result
    if len(credentials) == 2:
        # Both `token` and `password` present: repair rather than guess which
        # one the user meant.
        return base_result(
            "invalid", issue_code="ambiguous_credentials", generated=generated
        )
    credential_field = credentials[0]
    authenticator = connection.get("authenticator")
    if authenticator is None:
        if credential_field == "token":
            # Without an authenticator the connector performs a password
            # login and never reads `token` — this shape cannot sign in.
            return base_result(
                "invalid",
                issue_code="unsupported_credential_shape",
                generated=generated,
            )
        return base_result("complete", generated=generated)
    if str(authenticator).strip().upper() == "PROGRAMMATIC_ACCESS_TOKEN":
        if credential_field == "password":
            if generated and is_literal_migratable_legacy(text):
                # Legacy generated shape: the PAT authenticator makes the
                # connector read the credential from `token`, so a `password`
                # credential sends a null token and Snowflake rejects the
                # login. Enable-time import migrates this exact shape
                # automatically; rotation rewrites it too.
                return base_result(
                    "complete",
                    issue_code="legacy_pat_credential",
                    generated=generated,
                )
            # A hand-written (or hand-edited) file with the same defect is not
            # ours to rewrite — route to repair with a fresh token.
            return base_result(
                "invalid",
                issue_code="pat_credential_key_mismatch",
                generated=generated,
            )
        return base_result("complete", generated=generated)
    return base_result(
        "invalid", issue_code="unsupported_authenticator", generated=generated
    )


def is_literal_migratable_legacy(text: str) -> bool:
    """True only for shapes the enable-time import migration will rewrite."""
    if "'''" in text or '"""' in text:
        return False
    lines = text.splitlines()
    headers = [line for line in lines if re.match(r"^\s*\[", line)]
    if len(headers) != 1 or headers[0].strip() != "[default]":
        return False
    has_authenticator_line = any(
        re.match(r'^authenticator\s*=\s*"PROGRAMMATIC_ACCESS_TOKEN"\s*$', line)
        for line in lines
    )
    password_lines = [line for line in lines if re.match(r"^password\s*=", line)]
    token_lines = [line for line in lines if re.match(r"^token\s*=", line)]
    return has_authenticator_line and len(password_lines) == 1 and not token_lines


def valid_mcp_shape(parsed: object) -> bool:
    if not isinstance(parsed, dict):
        return False
    if not isinstance(parsed.get("other_services"), dict):
        return False
    if not isinstance(parsed.get("sql_statement_permissions"), list):
        return False
    for optional_list in ("agent_services", "analyst_services"):
        if optional_list in parsed and not isinstance(parsed[optional_list], list):
            return False
    return True


def classify_mcp_without_yaml(text: str) -> dict[str, object]:
    """Conservative fallback for development hosts without the Agent VM dependency."""
    if not text.strip() or any(marker in text for marker in ("\x00", "\t", "!!", "&", "*")):
        return base_result("invalid", issue_code="parse_error")
    top_level_keys = {
        match.group(1)
        for match in re.finditer(r"(?m)^([A-Za-z_][A-Za-z0-9_-]*):(?:\s.*)?$", text)
    }
    if not {"other_services", "sql_statement_permissions"}.issubset(top_level_keys):
        return base_result("invalid", issue_code="invalid_shape")
    bracket_check = re.sub(r"(?m)^[A-Za-z_][A-Za-z0-9_-]*:\s*\[\]\s*$", "", text)
    if any(character in bracket_check for character in ("{", "}", "[", "]")):
        return base_result("invalid", issue_code="parse_error")
    generated = text.startswith("# Generated by Portico Snowflake Setup.")
    if not generated:
        return base_result("custom_valid")
    trust_kit = "service_name: TRUST_KIT_AGENT" in text or "semantic_model: TRUST_KIT" in text
    return base_result("generated_trust_kit" if trust_kit else "generated_read_only")


def classify_mcp_config(path: Path) -> dict[str, object]:
    raw, issue = read_fixed_file(path)
    if issue == "absent":
        return base_result("absent")
    if issue:
        return base_result("invalid", issue_code=issue)
    try:
        text = (raw or b"").decode("utf-8")
    except UnicodeDecodeError:
        return base_result("invalid", issue_code="invalid_utf8")
    if yaml is None:
        return classify_mcp_without_yaml(text)
    try:
        parsed = yaml.safe_load(text)
    except yaml.YAMLError:
        return base_result("invalid", issue_code="parse_error")
    if not valid_mcp_shape(parsed):
        return base_result("invalid", issue_code="invalid_shape")

    generated = text.startswith("# Generated by Portico Snowflake Setup.")
    if not generated:
        return base_result("custom_valid")
    agent_services = parsed.get("agent_services") or []
    analyst_services = parsed.get("analyst_services") or []
    trust_kit = any(
        isinstance(item, dict)
        and (
            item.get("service_name") == "TRUST_KIT_AGENT"
            or item.get("semantic_model") == "TRUST_KIT"
        )
        for item in [*agent_services, *analyst_services]
    )
    return base_result("generated_trust_kit" if trust_kit else "generated_read_only")


def overall_state(connections_state: str, mcp_state: str) -> str:
    connection_usable = connections_state in {"complete", "secure_stub"}
    mcp_usable = mcp_state in {
        "generated_read_only",
        "generated_trust_kit",
        "custom_valid",
    }
    if connections_state == "absent" and mcp_state == "absent":
        return "empty"
    if connection_usable and mcp_state == "absent":
        return "connection_only"
    if connections_state == "absent" and mcp_usable:
        return "config_only"
    if connection_usable and mcp_usable:
        return "candidate_ready"
    return "ambiguous"


def main() -> int:
    try:
        args = parse_args()
        output_dir = Path(args.output_dir)
        connections = classify_connections(output_dir / "connections.toml")
        mcp_config = classify_mcp_config(output_dir / "mcp_config.yaml")
        result = {
            "success": True,
            "connections": connections,
            "mcp_config": mcp_config,
            "overall_state": overall_state(
                str(connections["state"]),
                str(mcp_config["state"]),
            ),
        }
    except Exception:
        result = {
            "success": False,
            "error_code": "inspection_failed",
        }
    print(json.dumps(result, sort_keys=True, separators=(",", ":")))
    return 0 if result.get("success") else 1


if __name__ == "__main__":
    raise SystemExit(main())
