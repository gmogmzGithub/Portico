#!/usr/bin/env python3
"""Create or update Snowflake MCP files without exposing connection values."""

from __future__ import annotations

import argparse
import json
import os
from pathlib import Path
import re
import stat
import tempfile
import tomllib
import urllib.error
import urllib.request


DEFAULT_ACCOUNT = "PORTICOORG-PORTICO"
# The token flow mints single-role PATs (PUBLIC unless the user granted another
# role); the connection's role must match the token's role restriction or
# Snowflake rejects the sign-in. With authenticator PROGRAMMATIC_ACCESS_TOKEN
# the connector reads the credential from `token` (AuthByPAT(self._token)) —
# writing it under `password` sends a null token and Snowflake answers 394400
# "Programmatic access token is invalid". A bare `password` without an
# authenticator also works (PAT-as-password), which is why hand-written files
# shaped that way connect. The Snowflake MCP server resolves
# warehouse/database/schema from mcp_config.yaml, so the connection file uses
# these fixed placeholders.
DEFAULT_ROLE = "PUBLIC"
DEFAULT_UNSELECTED = "<none selected>"
MAX_CONFIG_BYTES = 1024 * 1024
MAX_TOKEN_BYTES = 64 * 1024
# Mirrors snowflake_inspect.py's stub detection for files already imported into
# secure storage by Portico.
SECURE_STUB_MARKER = (
    "# Portico imported this sensitive runtime file into secure storage."
)
LOGIN_REQUEST_TIMEOUT_SECONDS = 15
# The login host derives ONLY from the account field; the strict charset keeps
# the request on *.snowflakecomputing.com so the token can never be posted to
# an arbitrary endpoint. There is deliberately no URL/host override argument.
ACCOUNT_HOST_PATTERN = re.compile(r"^[A-Za-z0-9_-]{1,120}$")
MAX_SERVER_MESSAGE_CHARS = 300
# Snowflake error codes are short digit strings (e.g. "394400"); anything else
# in the code field is untrusted response content and gets dropped.
SERVER_CODE_PATTERN = re.compile(r"^[0-9A-Za-z_.-]{1,32}$")


class SetupError(Exception):
    def __init__(self, code: str, field: str | None = None):
        super().__init__(code)
        self.code = code
        self.field = field


class SafeArgumentParser(argparse.ArgumentParser):
    def error(self, _message: str) -> None:
        raise SetupError("invalid_arguments")


def parse_args() -> argparse.Namespace:
    parser = SafeArgumentParser(add_help=False)
    parser.add_argument(
        "--operation",
        choices=("all", "connections", "mcp-config", "rotate-token", "validate"),
        default="all",
    )
    parser.add_argument("--token-file")
    parser.add_argument("--user")
    parser.add_argument("--role", default=DEFAULT_ROLE)
    parser.add_argument("--warehouse", default=DEFAULT_UNSELECTED)
    parser.add_argument("--database", default=DEFAULT_UNSELECTED)
    parser.add_argument("--schema", default=DEFAULT_UNSELECTED)
    parser.add_argument("--account", default=DEFAULT_ACCOUNT)
    parser.add_argument("--mode", choices=("read-only", "trust-kit"), default="trust-kit")
    parser.add_argument("--output-dir", default="/work")
    parser.add_argument("--replace-existing", action="store_true")
    return parser.parse_args()


def clean_required(value: str | None, field: str) -> str:
    raw = str(value or "").strip()
    if not raw:
        raise SetupError("missing_required_field", field)
    if any(character in raw for character in "\r\n\t\x00"):
        raise SetupError("invalid_field", field)
    return " ".join(raw.split())


def read_private_text(path: Path, *, maximum_bytes: int, error_prefix: str) -> str:
    try:
        metadata = path.lstat()
    except FileNotFoundError as error:
        raise SetupError(f"{error_prefix}_missing") from error
    except OSError as error:
        raise SetupError(f"{error_prefix}_unavailable") from error
    if not stat.S_ISREG(metadata.st_mode):
        raise SetupError(f"{error_prefix}_unsafe_file")
    if metadata.st_size > maximum_bytes:
        raise SetupError(f"{error_prefix}_too_large")
    try:
        return path.read_text(encoding="utf-8")
    except (OSError, UnicodeError) as error:
        raise SetupError(f"{error_prefix}_unreadable") from error


def read_pat(token_file: str | None) -> str:
    if not token_file:
        raise SetupError("token_file_required")
    token = read_private_text(
        Path(token_file),
        maximum_bytes=MAX_TOKEN_BYTES,
        error_prefix="token_file",
    ).strip()
    if not token or "\x00" in token:
        raise SetupError("token_file_invalid")
    return token


def toml_quote(value: str) -> str:
    return json.dumps(value, ensure_ascii=True)


def render_connections(
    *,
    account: str,
    user: str,
    role: str,
    warehouse: str,
    database: str,
    schema: str,
    pat: str,
) -> str:
    return "\n".join(
        [
            "# Generated by Portico Snowflake Setup.",
            "# Do not share this file. It contains a Snowflake programmatic access token.",
            "",
            "[default]",
            f"account = {toml_quote(account)}",
            f"user = {toml_quote(user)}",
            'authenticator = "PROGRAMMATIC_ACCESS_TOKEN"',
            f"token = {toml_quote(pat)}",
            f"role = {toml_quote(role)}",
            f"warehouse = {toml_quote(warehouse)}",
            f"database = {toml_quote(database)}",
            f"schema = {toml_quote(schema)}",
            "",
        ]
    )


