def assert_replace_allowed(path: Path, replace_existing: bool) -> None:
    try:
        metadata = path.lstat()
    except FileNotFoundError:
        return
    except OSError as error:
        raise SetupError("target_unavailable") from error
    if not stat.S_ISREG(metadata.st_mode):
        raise SetupError("target_unsafe_file")
    if not replace_existing:
        raise SetupError("target_exists")


def stage_private_file(path: Path, content: str) -> Path:
    path.parent.mkdir(parents=True, exist_ok=True)
    descriptor, temporary_name = tempfile.mkstemp(prefix=f".{path.name}.", dir=path.parent)
    temporary_path = Path(temporary_name)
    try:
        os.fchmod(descriptor, stat.S_IRUSR | stat.S_IWUSR)
        with os.fdopen(descriptor, "w", encoding="utf-8") as handle:
            handle.write(content)
            handle.flush()
            os.fsync(handle.fileno())
        return temporary_path
    except Exception:
        try:
            os.close(descriptor)
        except OSError:
            pass
        temporary_path.unlink(missing_ok=True)
        raise


def install_staged_files(staged: list[tuple[Path, Path]]) -> None:
    try:
        for temporary_path, target_path in staged:
            os.replace(temporary_path, target_path)
            target_path.chmod(stat.S_IRUSR | stat.S_IWUSR)
    finally:
        for temporary_path, _target_path in staged:
            temporary_path.unlink(missing_ok=True)


def rotate_connection_token(connections_path: Path, pat: str) -> str:
    text = read_private_text(
        connections_path,
        maximum_bytes=MAX_CONFIG_BYTES,
        error_prefix="connections_file",
    )
    if text.splitlines()[:1] == [SECURE_STUB_MARKER]:
        raise SetupError("connections_file_stub")
    try:
        parsed = tomllib.loads(text)
    except tomllib.TOMLDecodeError as error:
        raise SetupError("connections_file_invalid") from error
    default = parsed.get("default")
    if not isinstance(default, dict):
        raise SetupError("connections_file_invalid")
    # The generated shape names the PAT authenticator with the credential in
    # `token`; legacy generated files kept it in `password`, and hand-written
    # bare-password files (no authenticator) also authenticate. Any other
    # authenticator means the credential field could hold a real corporate
    # password, which rotation must not touch.
    authenticator = default.get("authenticator")
    if (
        authenticator is not None
        and str(authenticator).strip().upper() != "PROGRAMMATIC_ACCESS_TOKEN"
    ):
        raise SetupError("connections_file_invalid")

    lines = text.splitlines(keepends=True)
    default_start = None
    default_end = len(lines)
    for index, line in enumerate(lines):
        stripped = line.strip()
        if stripped == "[default]":
            default_start = index + 1
            continue
        if default_start is not None and index >= default_start and re.match(r"^\s*\[", line):
            default_end = index
            break
    if default_start is None:
        raise SetupError("connections_file_invalid")

    credential_indexes = [
        index
        for index in range(default_start, default_end)
        if re.match(r"^\s*(?:token|password)\s*=", lines[index])
    ]
    if len(credential_indexes) != 1:
        raise SetupError("connections_file_invalid")
    index = credential_indexes[0]
    newline = "\r\n" if lines[index].endswith("\r\n") else "\n"
    if not lines[index].endswith(("\n", "\r\n")):
        newline = ""
    indentation = re.match(r"^\s*", lines[index]).group(0)
    # Trust the PARSED authenticator, not a raw-line scan: a line inside a
    # multi-line string could otherwise masquerade as an authenticator and
    # flip a working bare-password file to a token shape the connector's
    # default password login cannot use.
    has_pat_authenticator = default.get("authenticator") is not None
    current_key = "token" if re.match(r"^\s*token\s*=", lines[index]) else "password"
    if current_key not in default:
        raise SetupError("connections_file_invalid")
    # With the PAT authenticator the connector reads the credential from
    # `token` (AuthByPAT) — rotating a legacy file that stored it under
    # `password` migrates the key so the rotated file actually authenticates.
    # Bare password files (no authenticator) keep their shape: PAT-as-password
    # also authenticates.
    new_key = "token" if has_pat_authenticator else current_key
    lines[index] = f"{indentation}{new_key} = {toml_quote(pat)}{newline}"
    return "".join(lines)


def load_default_connection(connections_path: Path) -> dict:
    text = read_private_text(
        connections_path,
        maximum_bytes=MAX_CONFIG_BYTES,
        error_prefix="connections_file",
    )
    if text.splitlines()[:1] == [SECURE_STUB_MARKER]:
        raise SetupError("connections_file_stub")
    try:
        parsed = tomllib.loads(text)
    except tomllib.TOMLDecodeError as error:
        raise SetupError("connections_file_invalid") from error
    default = parsed.get("default")
    if not isinstance(default, dict):
        raise SetupError("connections_file_invalid")
    return default


def snowflake_login_url(account: str) -> str:
    if not ACCOUNT_HOST_PATTERN.fullmatch(account):
        raise SetupError("invalid_field", "account")
    host_account = account.lower().replace("_", "-")
    return f"https://{host_account}.snowflakecomputing.com/session/v1/login-request"


def sanitize_server_message(message: object) -> str | None:
    if not isinstance(message, str):
        return None
    # Strip C0/C1 controls plus line/paragraph separators and bidi formatting
    # characters: the skill relays this text into chat, where a bidi override
    # could visually spoof instructions.
    cleaned = re.sub(
        r"[\x00-\x1f\x7f-\x9f\u2028\u2029\u200e\u200f\u202a-\u202e\u2066-\u2069]+",
        " ",
        message,
    ).strip()
    return cleaned[:MAX_SERVER_MESSAGE_CHARS] or None


def sanitize_server_code(code: object) -> str | None:
    if isinstance(code, bool) or not isinstance(code, (str, int)):
        return None
    text = str(code).strip()
    return text if SERVER_CODE_PATTERN.fullmatch(text) else None


def validate_connection(connections_path: Path) -> dict:
    connection = load_default_connection(connections_path)
    # Probe only PAT-shaped connections: the current generated shape
    # (authenticator PROGRAMMATIC_ACCESS_TOKEN + `token`), its broken legacy
    # sibling (the PAT stored under `password`), or a bare password file
    # (PAT-as-password also authenticates). Any other authenticator (e.g.
    # externalbrowser) means the credential field could hold a real corporate
    # password that must never be transmitted.
    authenticator = connection.get("authenticator")
    if (
        authenticator is not None
        and str(authenticator).strip().upper() != "PROGRAMMATIC_ACCESS_TOKEN"
    ):
        raise SetupError("connections_file_invalid")
    for field in ("account", "user"):
        value = connection.get(field)
        if not isinstance(value, str) or not value.strip():
            raise SetupError("missing_required_field", field)

    def credential_from(field):
        value = connection.get(field)
        return value if isinstance(value, str) and value.strip() else None

    # Mirror the connector exactly: with the PAT authenticator it reads the
    # credential from `token` only (AuthByPAT) — a PAT stored under `password`
    # is the legacy broken shape the connector cannot authenticate with, so
    # report it for migration instead of probing something the server will
    # not do. Without an authenticator it is a plain password login.
    if authenticator is not None:
        credential = credential_from("token")
        if credential is None:
            if credential_from("password") is not None:
                raise SetupError("legacy_pat_credential")
            raise SetupError("missing_required_field", "token")
        credential_fields = {
            "AUTHENTICATOR": "PROGRAMMATIC_ACCESS_TOKEN",
            "TOKEN": credential,
        }
    else:
        credential = credential_from("password")
        if credential is None:
            raise SetupError("missing_required_field", "password")
        credential_fields = {"PASSWORD": credential}
    request = urllib.request.Request(
        snowflake_login_url(connection["account"]),
        data=json.dumps(
            {
                "data": {
                    "ACCOUNT_NAME": connection["account"],
                    "LOGIN_NAME": connection["user"],
                    **credential_fields,
                }
            }
        ).encode("utf-8"),
        headers={"Content-Type": "application/json", "Accept": "application/json"},
        method="POST",
    )
    try:
        with urllib.request.urlopen(
            request, timeout=LOGIN_REQUEST_TIMEOUT_SECONDS
        ) as response:
            raw = response.read(MAX_CONFIG_BYTES)
    except urllib.error.HTTPError as error:
        # 5xx/429 are transient service problems, not a token verdict — do not
        # send the user off to re-mint a PAT for a Snowflake outage.
        if error.code == 429 or error.code >= 500:
            raise SetupError("snowflake_unavailable") from error
        # Other rejections can arrive as HTTP 4xx with a JSON body.
        raw = error.read(MAX_CONFIG_BYTES)
    except (urllib.error.URLError, TimeoutError, OSError) as error:
        raise SetupError("network_unreachable") from error
    try:
        body = json.loads(raw.decode("utf-8"))
    except (UnicodeError, json.JSONDecodeError) as error:
        raise SetupError("validation_unexpected_response") from error
    if not isinstance(body, dict):
        raise SetupError("validation_unexpected_response")
    if body.get("success") is True:
        # Never echo the body: a successful login response carries a session
        # token.
        return {"validation": "ok"}
    return {
        "validation": "auth_rejected",
        "snowflake_code": sanitize_server_code(body.get("code")),
        "snowflake_message": sanitize_server_message(body.get("message")),
    }


def main() -> int:
    staged: list[tuple[Path, Path]] = []
    try:
        args = parse_args()
        output_dir = Path(args.output_dir)
        connections_path = output_dir / "connections.toml"
        mcp_config_path = output_dir / "mcp_config.yaml"
        operation = args.operation
        written: list[str] = []

        if operation == "validate":
            verdict = validate_connection(connections_path)
            if verdict["validation"] != "ok":
                print(
                    json.dumps(
                        {
                            "success": False,
                            "error_code": "auth_rejected",
                            "snowflake_code": verdict["snowflake_code"],
                            "snowflake_message": verdict["snowflake_message"],
                        },
                        sort_keys=True,
                        separators=(",", ":"),
                    ),
                    file=os.sys.stderr,
                )
                return 1
            print(
                json.dumps(
                    {"success": True, "operation": "validate", "validated": True},
                    sort_keys=True,
                    separators=(",", ":"),
                )
            )
            return 0

        if operation in {"all", "connections"}:
            assert_replace_allowed(connections_path, args.replace_existing)
        if operation in {"all", "mcp-config"}:
            assert_replace_allowed(mcp_config_path, args.replace_existing)

        if operation in {"all", "connections"}:
            pat = read_pat(args.token_file)
            connection_content = render_connections(
                account=clean_required(args.account, "account"),
                user=clean_required(args.user, "user"),
                role=clean_required(args.role, "role"),
                warehouse=clean_required(args.warehouse, "warehouse"),
                database=clean_required(args.database, "database"),
                schema=clean_required(args.schema, "schema"),
                pat=pat,
            )
            staged.append((stage_private_file(connections_path, connection_content), connections_path))
            written.append(connections_path.name)

        if operation in {"all", "mcp-config"}:
            mcp_content = (
                render_trust_kit_config() if args.mode == "trust-kit" else render_read_only_config()
            )
            staged.append((stage_private_file(mcp_config_path, mcp_content), mcp_config_path))
            written.append(mcp_config_path.name)

        if operation == "rotate-token":
            pat = read_pat(args.token_file)
            rotated = rotate_connection_token(connections_path, pat)
            staged.append((stage_private_file(connections_path, rotated), connections_path))
            written.append(connections_path.name)

        install_staged_files(staged)
        result = {
            "success": True,
            "operation": operation,
            "mode": args.mode,
            "files_written": written,
        }
        print(json.dumps(result, sort_keys=True, separators=(",", ":")))
        return 0
    except SetupError as error:
        result: dict[str, object] = {"success": False, "error_code": error.code}
        if error.field:
            result["field"] = error.field
        print(json.dumps(result, sort_keys=True, separators=(",", ":")), file=os.sys.stderr)
        return 1
    except Exception:
        print(
            json.dumps(
                {"success": False, "error_code": "setup_failed"},
                sort_keys=True,
                separators=(",", ":"),
            ),
            file=os.sys.stderr,
        )
        return 1
    finally:
        for temporary_path, _target_path in staged:
            temporary_path.unlink(missing_ok=True)


if __name__ == "__main__":
    raise SystemExit(main())
